"""Bundle the YAML entries in data/ into site/data.js for the static front-end.

Usage: python scripts/build_site.py

References are resolved here (author names, venue names, earliest year of a paper),
so the front-end only has to render. The output is a plain script that sets
window.ATLAS_DATA, which also works when the page is opened directly from disk.
"""
import hashlib
import json
import re
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
PROBLEM_ORDER = ["maximal-matching", "mis", "vertex-coloring", "edge-coloring", "network-decomposition",
                 "degree-splitting"]


def load(folder):
    return {p.stem: yaml.safe_load(p.read_text(encoding="utf-8"))
            for p in sorted((ROOT / "data" / folder).glob("*.yaml"))}


def main():
    authors, venues, papers, results, reductions = (
        load(f) for f in ("authors", "venues", "papers", "results", "reductions"))

    out_papers = {}
    for pid, p in papers.items():
        versions = sorted(p["versions"], key=lambda v: v["year"])
        out_papers[pid] = {
            "id": pid,
            "label": p["label"],
            "title": p["title"],
            "authors": [authors[a]["name"] for a in p["authors"]],
            # Author ids are "lastname-firstname", so they sort the bibliography by surname.
            "sort_key": " ".join(p["authors"]) + f" {versions[0]['year']}",
            "public_url": p.get("public_url"),
            "versions": [{
                "type": v["type"],
                "venue": venues[v["venue"]].get("short_name", venues[v["venue"]]["name"]),
                "venue_name": venues[v["venue"]]["name"],
                "year": v["year"],
                "title": v.get("title"),
                "doi": v.get("doi"),
                "arxiv": v.get("arxiv"),
            } for v in versions],
            # The entry as stored in data/papers/, for the edit form in the bibliography.
            "raw": p,
        }

    out_results = sorted(results.values(), key=lambda r: (r["year"], r["id"]))
    out_results = [r for r in out_results if r.get("status") == "approved"]

    out_reductions = sorted(
        (r for r in reductions.values() if r.get("status") == "approved"),
        key=lambda r: (PROBLEM_ORDER.index(r["from"]["problem"]), PROBLEM_ORDER.index(r["to"]["problem"]), r["id"]))

    bundle = {
        "papers": out_papers, "results": out_results, "reductions": out_reductions,
        # Choices for the paper edit form.
        "authors": {aid: a["name"] for aid, a in sorted(authors.items(), key=lambda kv: kv[0])},
        "venues": {vid: {"name": v["name"], "short_name": v.get("short_name"), "type": v["type"]}
                   for vid, v in sorted(venues.items(), key=lambda kv: kv[0])},
    }
    target = ROOT / "site" / "data.js"
    target.write_text(
        "// Generated by scripts/build_site.py from data/. Do not edit by hand.\n"
        "window.ATLAS_DATA = " + json.dumps(bundle, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8", newline="\n")
    print(f"Wrote {target.relative_to(ROOT)}: {len(out_results)} results, "
          f"{len(out_reductions)} reductions, {len(out_papers)} papers")
    stamp_assets()


def stamp_assets():
    """Append ?v=<content hash> to local script, stylesheet and favicon links in every page.

    Browsers otherwise keep using cached copies of data.js etc. after a rebuild.
    """
    site = ROOT / "site"
    assets = ("data.js", "asymptotics.js", "app.js", "style.css", "favicon.svg")
    versions = {a: hashlib.sha1((site / a).read_bytes()).hexdigest()[:10] for a in assets if (site / a).exists()}
    pattern = re.compile(r'(src|href)="(' + "|".join(re.escape(a) for a in versions) + r')(\?v=[0-9a-f]*)?"')
    for page in sorted(site.glob("*.html")):
        text = page.read_text(encoding="utf-8")
        new = pattern.sub(lambda m: f'{m.group(1)}="{m.group(2)}?v={versions[m.group(2)]}"', text)
        if new != text:
            page.write_text(new, encoding="utf-8", newline="\n")
            print(f"Updated asset versions in {page.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
